## A realistic page: lots of static markup plus variables, an if and a loop.
proc benchPage(title: string, items: seq[string], loggedIn: bool): string =
  compileTemplateStr("""
<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <title>{{title}}</title>
</head>
<body>
  <header>
    <h1>{{title}}</h1>
  </header>
  {% if loggedIn %}
    <p class="welcome">Welcome back, {{title}}!</p>
  {% else %}
    <p class="login">Please log in.</p>
  {% endif %}
  <ul class="items">
  {% for item in items %}
    <li class="item">{{item}}</li>
  {% endfor %}
  </ul>
  <footer>
    <p>Generated by nimja. All rights reserved.</p>
  </footer>
</body>
</html>
""")

## Static-heavy body with a single variable (preallocation path).
proc benchStatic(version: int): string =
  compileTemplateStr(staticBody & "<p>version {{version}}</p>")

## Variables only: `$`/append heavy, no static text at all.
proc benchVars(a, b, c, d, e, f, g, h: string): string =
  compileTemplateStr("{{a}}{{b}}{{c}}{{d}}{{e}}{{f}}{{g}}{{h}}")

## A template-defined proc called three times.
proc benchProc(name: string): string =
  compileTemplateStr("{% proc greet(n: string): string = %}Hello, {{n}}! Welcome aboard.{% end %}{{greet(name)}}{{greet(name)}}{{greet(name)}}")

## Large template-proc body: its own result is preallocated (>= 64 static chars).
proc benchBigProc(n: string): string =
  compileTemplateStr("{% proc big(n: string): string = %}<section><header><h1>Title</h1></header><article><p>Some longer static paragraph that is part of the component body and is over the preallocation threshold.</p></article><footer>{{ n }}</footer></section>{% end %}{{ big(n) }}")

const
  cf1 = "alpha"
  cf2 = "beta"
  cf3 = "gamma"
  cf4 = "delta"

## A run of compile-time const variables (folded into the surrounding literal).
proc benchConstBlock(flag: bool): string =
  compileTemplateStr("{{cf1}}{{cf2}}{{cf3}}{{cf4}}{% if flag %}<b>on</b>{% endif %}")

## Const variables mixed with a runtime variable.
proc benchMixedConst(x: string): string =
  compileTemplateStr("{{cf1}} {{cf2}} {{cf3}} {{cf4}}{{x}}")

## Autoescaped output (htmlEscape on every variable), value with HTML chars.
proc benchEscape(x: string): string =
  compileTemplateStr("<p title=\"{{x}}\">{{x}}</p>", escapeWith = htmlEscape)

## Autoescaped output where the value has nothing to escape (the common case).
proc benchEscapePlain(x: string): string =
  compileTemplateStr("<h2>{{x}}</h2><p>{{x}}</p>", escapeWith = htmlEscape)

## `loop()` helper: Loop construction, cycle(), first/last checks.
proc benchLoop(rows: seq[string]): string =
  compileTemplateStr("""
<ul>
{% for (loop, row) in rows.loop() %}
  <li class="{{ loop.cycle(@["odd", "even"]) }}{% if loop.first %} first{% endif %}{% if loop.last %} last{% endif %}">{{ loop.index }}: {{row}}</li>
{% endfor %}
</ul>
""")

## Nested control flow over data.
proc benchNested(users: seq[(string, int)], flag: bool): string =
  compileTemplateStr("""
{% for user in users %}
  {% if user[1] >= 18 %}
    {% case flag %}{% of true %}<b>{{user[0]}}</b>{% else %}<i>{{user[0]}}</i>{% endcase %}
  {% else %}
    <span>{{user[0]}}</span>
  {% endif %}
{% endfor %}
""")

## Runtime helper filters (string processing) on a realistic value.
proc benchFilters(s: string): string =
  compileTemplateStr("{{ s.spaceless }}{{ s.nl2br }}{{ s.truncate(12) }}{{ s.slugify }}")

## Scalars of different types: `$`/formatting of int, float, bool, char.
proc benchScalars(n: int, f: float, b: bool, c: char): string =
  compileTemplateStr("{{n}}|{{f}}|{{b}}|{{c}}|{{n + 1}}|{{f * 2.0}}")

# ---------------------------------------------------------------------------
# Feature coverage (gate only, not timed)
# ---------------------------------------------------------------------------

proc featIf(x: int): string =
  compileTemplateStr("""{% if x < 0 %}neg{% elif x == 0 %}zero{% else %}pos{% endif %}""")

proc featCase(s: string): string =
  compileTemplateStr("""{% case s %}{% of "a" %}A{% of "b" %}B{% else %}other{% endcase %}""")

proc featWhile(): string =
  compileTemplateStr("""{% var cnt = 0 %}{% while cnt != 3 %}{% cnt.inc() %}{{cnt}}{% endwhile %}""")

proc featWhen(): string =
  compileTemplateStr("""{% when true %}T{% endwhen %}{% when false %}F{% endwhen %}""")

proc featScope(): string =
  compileTemplateStr("""{%- scope -%}{% let httpMethod = "POST" %}{{- httpMethod -}}{%- endscope -%}{%- let httpMethod = "FOO" -%}{{ httpMethod -}}""")

proc featProc(a: int, b: int = 7): string =
  compileTemplateStr("""{% proc add(x: int, y: int = 3): string = %}{{ x + y }}{% end %}{{ add(a) }}:{{ add(a, b) }}""")

proc featFunc(n: string): string =
  compileTemplateStr("""{% func upper(s: string): string = %}{{ s.toUpperAscii() }}{% end %}{{ upper(n) }}""")

proc featWhitespace(x: bool): string =
  compileTemplateStr("""
    {%- if x -%}
      yes
    {%- else -%}
      no
    {%- endif -%}
  """)

proc featFilters(s: string): string =
  compileTemplateStr("""{{ s|e }}|{{ s|safe }}|{{ s.truncate(5) }}|{{ s.slugify }}|{{ s.nl2br }}|{{ s.spaceless }}""")

proc featLiterals(): string =
  compileTemplateStr("""{{"literal"}}{{42}}{{true}}{% let x = "rt" %}{{x}}{# a comment #}""")

proc featEmptyLoop(rows: seq[string]): string =
  compileTemplateStr("""[{% for row in rows %}{{row}}{% endfor %}]""")

proc featUnicode(): string =
  compileTemplateStr("""äöü ß ñ 日本語 🎉 — «{{"guillemets"}}»""")

proc featCommentsAndEvals(x: string): string =
  compileTemplateStr("""{# before #}{% let y = x & "!" %}{# between #}{{y}}{# after #}{% if y.len > 2 %}{{ y.len }}{% endif %}""")

