proc renderAll*(): seq[(string, string)] =
  ## Every template rendered once with fixed inputs. The gate compares this
  ## between the candidate and the baseline build, byte for byte.
  let users = @[("alice", 30), ("bob", 17), ("carol", 18)]
  let rows = benchItems
  result = @[
    ("page-loggedIn", benchPage("Benchmark", benchItems, true)),
    ("page-anon", benchPage("", @[], false)),
    ("static", benchStatic(1234)),
    ("vars", benchVars("a", "b", "c", "d", "e", "f", "g", "h")),
    ("proc", benchProc("World")),
    ("bigProc", benchBigProc("World")),
    ("constBlock-on", benchConstBlock(true)),
    ("constBlock-off", benchConstBlock(false)),
    ("mixedConst", benchMixedConst("tail")),
    ("escape", benchEscape(benchUnsafe)),
    ("escape-plain", benchEscapePlain("plain text 123")),
    ("loop", benchLoop(rows)),
    ("loop-empty", benchLoop(@[])),
    ("nested", benchNested(users, true)),
    ("nested-false", benchNested(users, false)),
    ("filters", benchFilters(benchFilterText)),
    ("scalars", benchScalars(-42, 3.5, true, 'x')),
    ("if", featIf(-1) & featIf(0) & featIf(1)),
    ("case", featCase("a") & featCase("b") & featCase("z")),
    ("while", featWhile()),
    ("when", featWhen()),
    ("scope", featScope()),
    ("proc-defaults", featProc(1) & featProc(1, 2)),
    ("func", featFunc("hello")),
    ("whitespace-true", featWhitespace(true)),
    ("whitespace-false", featWhitespace(false)),
    ("filters-e", featFilters("a<b> c\\nd")),
    ("literals", featLiterals()),
    ("empty-loop", featEmptyLoop(@[])),
    ("unicode", featUnicode()),
    ("comments", featCommentsAndEvals("x")),
  ]
