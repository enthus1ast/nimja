## Fixed template corpus for the runtime-rendering experiment.
##
## This file is `include`d by `driver.nim`, which imports the candidate (or
## baseline) `nimja` module first, so it must NOT import nimja itself:
## everything here is compiled by the code generator under test.
##
## The `bench*` procs are the timed workloads. `renderAll` renders every
## template (timed ones and feature-coverage ones) with fixed inputs; the gate
## compares that output byte-for-byte between candidate and baseline.
##
## This file is FIXED. Do not modify it.

const benchItems = @["alpha", "beta", "gamma", "delta", "epsilon", "zeta",
                     "eta", "theta"]

const benchUnsafe = "A-<->-\"-&-'-b"

const benchFilterText = "  <p>some   text\nwith  spaces</p>  "

