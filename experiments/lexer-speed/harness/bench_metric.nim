## Primary metric: compile-time lexing speed (A/B against the current best).
##
## nimja lexes templates at compile time, inside the Nim VM. This program
## measures how long `nim c --compileOnly` takes for a generated fixture that
## imports the lexer under test and lexes the fixed 2 MB corpus in a `static:`
## block.
##
## The fixture is compiled once against the candidate lexer ($CAND_LEX, a copy
## of the working tree file) and once against the last kept commit ($BASE_LEX),
## in interleaved rounds (candidate, baseline, candidate, baseline, ...) so
## machine drift, frequency changes and load affect both sides equally. The
## metric is
##
##   speedup = min(baseline_ms) / min(candidate_ms)
##
## `baseline_ms`/`candidate_ms` are total `nim c --compileOnly` wall clock
## times: roughly 0.6 s of fixed front-end/startup overhead plus the VM time
## spent lexing the corpus. Measuring the noop overhead separately and
## subtracting it turned out to be much noisier (a noop compile can vary by
## 400 ms between runs on a busy machine), so the raw interleaved total is used.
##
## The fixture imports the lexer through an explicit relative path (a copy
## placed next to the fixture), NOT through the module search path, so a
## machine-wide nim.cfg cannot shadow the lexer under test.
##
## Environment:
##   CAND_LEX, BASE_LEX  primary module source files (required)
##   REPS                interleaved repetitions per side (default 10)
##   CT_TIMEOUT          seconds per `nim c` invocation (default 300)
##
## Exit code 0 = ok, 2 = fixture failed to compile, 3 = timeout.
##
## This file is FIXED. Do not modify it.
import std/[os, osproc, strutils, monotimes, times, strformat]

# Runtime throughput (informational) uses the candidate lexer.
import ../../../src/nimja/lexer

const
  harnessDir = currentSourcePath().parentDir
  repoRoot = harnessDir.parentDir.parentDir.parentDir
  workDir = repoRoot / "experiments" / "lexer-speed" / ".work"
  corpusPath = harnessDir / "corpus" / "corpus.txt"
  corpus = staticRead("corpus/corpus.txt")

const ctLexTemplate = """
## Generated by bench_metric.nim -- do not edit.
import ./nimja_lexer

const corpus = staticRead("CORPUS")

static:
  var tokens = 0
  var valueBytes = 0
  for t in lex(corpus):
    inc tokens
    valueBytes += t.value.len
  doAssert tokens > 0
  doAssert valueBytes > 0
"""

proc envOr(name, fallback: string): string =
  result = getEnv(name)
  if result.len == 0:
    result = fallback

let
  candLex = envOr("CAND_LEX", "")
  baseLex = envOr("BASE_LEX", "")
  reps = try:
      parseInt(envOr("REPS", "10"))
    except ValueError:
      10
  ctTimeout = envOr("CT_TIMEOUT", "600")

if candLex.len == 0 or baseLex.len == 0:
  stderr.writeLine "CAND_LEX and BASE_LEX must be set"
  quit(4)

proc prepare(dir, lexerSource: string) =
  ## One side: a copy of the lexer under test plus both generated fixtures.
  createDir(dir)
  copyFile(lexerSource, dir / "nimja_lexer.nim")
  writeFile(dir / "ct_lex.nim", ctLexTemplate.replace("CORPUS", corpusPath))

let
  candDir = workDir / "cand"
  baseDir = workDir / "base"

prepare(candDir, candLex)
prepare(baseDir, baseLex)

proc compileMs(fixtureDir, fixture, nimcache: string): float =
  ## Wall clock time of one `nim c --compileOnly` of `fixture`.
  let cmd = "timeout -s KILL " & ctTimeout & " nim c --compileOnly " &
            "--skipParentCfg:on --hints:off --warnings:off " &
            "--nimcache:" & quoteShell(nimcache) & " " &
            quoteShell(fixtureDir / fixture)
  let t0 = getMonoTime()
  let (output, code) = execCmdEx(cmd, options = {poUsePath, poStdErrToStdOut})
  let t1 = getMonoTime()
  if code != 0:
    stderr.writeLine "compile failed (exit ", code, "): ", cmd
    stderr.writeLine output
    if code == 137 or code == 124:
      quit(3)
    quit(2)
  result = (t1 - t0).inMicroseconds.float / 1_000.0

proc minOf(s: seq[float]): float =
  result = float.high
  for v in s:
    if v < result:
      result = v

proc lexRuntime(s: string): int =
  for t in lex(s):
    result += t.value.len

# --- interleaved A/B of the compile-time fixture --------------------------
var
  candTimes, baseTimes: seq[float]

# Alternate which side goes first in each round so neither side systematically
# pays for a cold cache or a frequency transition.
for i in 0 ..< reps:
  if (i and 1) == 0:
    candTimes.add compileMs(candDir, "ct_lex.nim", workDir / "nc-cand-lex")
    baseTimes.add compileMs(baseDir, "ct_lex.nim", workDir / "nc-base-lex")
  else:
    baseTimes.add compileMs(baseDir, "ct_lex.nim", workDir / "nc-base-lex")
    candTimes.add compileMs(candDir, "ct_lex.nim", workDir / "nc-cand-lex")

let
  candMs = minOf(candTimes)
  baseMs = minOf(baseTimes)
  speedup = if candMs > 0: baseMs / candMs else: 0.0

# --- informational runtime throughput (C backend) -------------------------
var acc = 0
for i in 0 ..< 3: # warm up
  acc += lexRuntime(corpus)
var best = float.high
for i in 0 ..< 20:
  let t0 = getMonoTime()
  acc += lexRuntime(corpus)
  let t1 = getMonoTime()
  let ms = (t1 - t0).inMicroseconds.float / 1_000.0
  if ms < best:
    best = ms
let mbps = (corpus.len.float / (1024.0 * 1024.0)) / (best / 1000.0)

echo "---"
echo &"candidate_ms: {candMs:.1f}"
echo &"baseline_ms: {baseMs:.1f}"
echo &"speedup: {speedup:.4f}"
echo &"rt_mbps: {mbps:.1f}"
echo &"reps: {reps}"
if acc < 0:
  echo "unreachable ", acc
