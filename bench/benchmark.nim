## Nimja render benchmark.
##
## Measures the *generated* (runtime) code, not compile time.
## Run with:
##   nimble bench
## or directly:
##   nim c -r -d:release bench/benchmark.nim
##
## Requires the treeform/benchy checkout next to this repo
## (`../benchy/src`, see bench/config.nims); if it is installed via nibmle,
## drop the second path switch.
import benchy

import ../src/nimja

# ---------------------------------------------------------------------------
# A realistic page: lots of static markup plus variables, an if and a loop.
# ---------------------------------------------------------------------------
proc page(title: string, items: seq[string], loggedIn: bool): string =
  compileTemplateStr("""
<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <title>{{title}}</title>
</head>
<body>
  <header>
    <h1>{{title}}</h1>
  </header>
  {% if loggedIn %}
    <p class="welcome">Welcome back, {{title}}!</p>
  {% else %}
    <p class="login">Please log in.</p>
  {% endif %}
  <ul class="items">
  {% for item in items %}
    <li class="item">{{item}}</li>
  {% endfor %}
  </ul>
  <footer>
    <p>Generated by nimja. All rights reserved.</p>
  </footer>
</body>
</html>
""")

# ---------------------------------------------------------------------------
# Static-heavy: a long constant body with a single variable. Exercises
# `newStringOfCap` (F-2/F-5).
# ---------------------------------------------------------------------------
const staticBody = """
<!DOCTYPE html>
<html>
<head><title>Static page</title></head>
<body>
  <nav><a href="/">home</a> | <a href="/about">about</a> | <a href="/contact">contact</a></nav>
  <main>
    <h1>Static content</h1>
    <p>Lorem ipsum dolor sit amet, consectetur adipiscing elit. Sed do eiusmod
    tempor incididunt ut labore et dolore magna aliqua. Ut enim ad minim veniam,
    quis nostrud exercitation ullamco laboris nisi ut aliquip ex ea commodo.</p>
    <p>Duis aute irure dolor in reprehenderit in voluptate velit esse cillum
    dolore eu fugiat nulla pariatur. Excepteur sint occaecat cupidatat non
    proident, sunt in culpa qui officia deserunt mollit anim id est laborum.</p>
    <section><article><h2>One</h2><p>Alpha beta gamma delta epsilon.</p></article></section>
    <section><article><h2>Two</h2><p>Zeta eta theta iota kappa lambda.</p></article></section>
  </main>
  <footer><p>Footer text that is also completely static.</p></footer>
</body>
</html>
"""

proc staticPage(version: int): string =
  compileTemplateStr(staticBody & "<p>version {{version}}</p>")

# ---------------------------------------------------------------------------
# Variables only: exercises the `$`/append code (F-4) and cap(0) (F-5).
# ---------------------------------------------------------------------------
proc vars(a, b, c, d, e, f, g, h: string): string =
  compileTemplateStr("{{a}}{{b}}{{c}}{{d}}{{e}}{{f}}{{g}}{{h}}")

# ---------------------------------------------------------------------------
# Two procs with the *same* template string: the second is a cache hit and
# used to lose its `newStringOfCap` (F-2).
# ---------------------------------------------------------------------------
proc cacheA(x: int): string =
  compileTemplateStr("<p>some constant text here {{x}} and more constant text</p>")

proc cacheB(x: int): string =
  compileTemplateStr("<p>some constant text here {{x}} and more constant text</p>")

# ---------------------------------------------------------------------------
# Template-defined proc: exercises per-proc preallocation (F-3).
# ---------------------------------------------------------------------------
proc withProc(name: string): string =
  compileTemplateStr("{% proc greet(n: string): string = %}Hello, {{n}}! Welcome aboard.{% end %}{{greet(name)}}{{greet(name)}}{{greet(name)}}")

const items = @["alpha", "beta", "gamma", "delta", "epsilon", "zeta", "eta", "theta"]

# Render each scenario many times per timed iteration so the per-call time is
# measurable. Results are accumulated into `acc` so the calls are not
# dead-code-eliminated (`benchy.keep` is just `discard`).
const inner = 10_000

var acc: int

proc benchPage() =
  for i in 0 ..< inner:
    acc += page("Benchmark", items, true).len

proc benchStatic() =
  for i in 0 ..< inner:
    acc += staticPage(1234).len

proc benchVars() =
  for i in 0 ..< inner:
    acc += vars("a", "b", "c", "d", "e", "f", "g", "h").len

proc benchCache() =
  for i in 0 ..< inner:
    acc += cacheA(1).len
    acc += cacheB(2).len

proc benchProc() =
  for i in 0 ..< inner:
    acc += withProc("World").len

timeIt "page (8 items)", 50:
  benchPage()

timeIt "static (long body)", 50:
  benchStatic()

timeIt "vars (8 variables)", 50:
  benchVars()

timeIt "cache hit (same template twice)", 50:
  benchCache()

timeIt "template proc", 50:
  benchProc()

# keep `acc` alive
if acc < 0: echo "unreachable ", acc
